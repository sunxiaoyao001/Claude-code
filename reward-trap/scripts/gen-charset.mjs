// Collects every non-ASCII character used in src/ so fonts can be preloaded before the first frame.
import {readFileSync, readdirSync, statSync, writeFileSync, mkdirSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const out = join(root, 'generated', 'charset.ts');
const chars = new Set();

const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (p === out) continue;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|json)$/.test(name)) {
      for (const ch of readFileSync(p, 'utf8')) if (ch.codePointAt(0) > 0x7f) chars.add(ch);
    }
  }
};
walk(root);
for (let c = 0x20; c < 0x7f; c++) chars.add(String.fromCharCode(c));

const list = [...chars].filter((c) => !/\s/.test(c) || c === ' ').sort();
mkdirSync(dirname(out), {recursive: true});
writeFileSync(
  out,
  `// Generated by scripts/gen-charset.mjs — do not edit.\nexport const CHARSET = ${JSON.stringify(list.join(''))};\n`,
);
console.log(`charset: ${list.length} glyphs -> ${out}`);
