// 把多段地图拼成一张：每段底部对齐，顶部用 pad 字符补齐
function seg(str) {
  return str.split('\n').map((r) => r.trim()).filter((r) => r.length);
}

function joinSegs(segs, h, pad) {
  const rows = Array.from({ length: h }, () => '');
  for (const s of segs) {
    const w = Math.max(...s.map((r) => r.length));
    const off = h - s.length;
    for (let y = 0; y < h; y++) {
      let r = y >= off ? s[y - off] : pad.repeat(w);
      if (r.length < w) r += r[r.length - 1].repeat(w - r.length);
      rows[y] += r;
    }
  }
  return rows;
}

// 雪塔：用代码搭的竖向关卡
function buildTower() {
  const W = 24, H = 66;
  const g = Array.from({ length: H }, () => Array(W).fill('.'));
  const put = (x, y, c) => { g[y][x] = c; };
  const hl = (x0, x1, y, c) => { for (let x = x0; x <= x1; x++) g[y][x] = c; };
  for (let y = 0; y < H; y++) { g[y][0] = '#'; g[y][W - 1] = '#'; }
  hl(0, W - 1, 64, '#');
  hl(0, W - 1, 65, '#');
  put(3, 63, 'P'); put(6, 63, '!');
  hl(4, 8, 60, '-'); hl(5, 7, 58, 'o');
  hl(11, 15, 57, '-'); hl(12, 14, 55, 'o');
  hl(17, 21, 54, '-'); hl(18, 20, 52, 'o');
  put(15, 50, 'f');
  hl(9, 13, 51, '-');
  hl(1, 5, 48, 'I'); put(2, 47, 'C');
  put(8, 46, 'N'); put(8, 47, '|'); put(8, 35, '|');
  put(12, 44, 'o'); put(12, 41, 'o'); put(12, 38, 'o');
  put(4, 41, 'b'); put(19, 43, 'b');
  hl(13, 18, 35, '#'); hl(14, 17, 34, 'o');
  hl(6, 10, 32, '-');
  hl(14, 21, 29, '#'); put(16, 22, 'T');
  hl(8, 12, 26, '-'); hl(9, 11, 24, 'o');
  hl(2, 6, 23, '-');
  hl(8, 11, 20, '-');
  put(17, 20, '*');
  hl(13, 18, 17, '#'); put(15, 16, 'C');
  hl(6, 9, 14, '-');
  hl(1, 3, 11, '='); put(2, 10, '*');
  hl(19, 22, 14, '-');
  hl(14, 17, 11, 'I');
  hl(18, 21, 8, '-'); put(21, 4, '*');
  put(9, 12, 'f');
  put(11, 9, 'b');
  hl(12, 15, 6, '-'); hl(12, 15, 5, 'o');
  hl(4, 10, 3, '#'); put(7, 2, 'G');
  return g.map((r) => r.join(''));
}

