/** 射线法判断点是否在多边形内 */
const inPoly = (lat: number, lon: number, poly: LL[]) => {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i];
    const [yj, xj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

/** 南极洲不画：从这个俯角看，极地点阵会挤成一圈圈同心弧，像靶子 */
const isLand = (lat: number, lon: number) => LAND.some((p) => inPoly(lat, lon, p)) && !HOLES.some((p) => inPoly(lat, lon, p));

/** 4° 经纬网格，陆地 / 海洋只算一次 */
const STEP = 4;
const GRID: {lat: number; lon: number; land: boolean}[] = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  for (let lon = -180; lon < 180; lon += STEP) GRID.push({lat, lon, land: isLand(lat, lon)});
}

const rad = (d: number) => (d * Math.PI) / 180;

const project = (lat: number, lon: number, lon0: number, lat0: number, R: number) => {
  const la = rad(lat);
  const dl = rad(lon - lon0);
  const p0 = rad(lat0);
  const x = R * Math.cos(la) * Math.sin(dl);
  const y = -R * (Math.sin(la) * Math.cos(p0) - Math.cos(la) * Math.sin(p0) * Math.cos(dl));
  const z = Math.sin(la) * Math.sin(p0) + Math.cos(la) * Math.cos(p0) * Math.cos(dl);
  return {x, y, z};
};

export const Globe: React.FC<{lon0: number; lat0?: number; R?: number; pins: Pin[]; frame: number}> = ({lon0, lat0 = -8, R = 300, pins, frame}) => {
  const dots: React.ReactNode[] = [];
  for (const g of GRID) {
    const p = project(g.lat, g.lon, lon0, lat0, R);
    if (p.z <= 0) continue;
    dots.push(
      g.land ? (
        <circle key={`${g.lat}:${g.lon}`} cx={p.x} cy={p.y} r={1.6 + 2.6 * p.z} fill={C.coopHot} opacity={0.25 + 0.65 * p.z} />
      ) : (
        <circle key={`${g.lat}:${g.lon}`} cx={p.x} cy={p.y} r={0.9 + 0.9 * p.z} fill={C.hud} opacity={0.08 + 0.2 * p.z} />
      ),
    );
  }
  return (
    <svg width={R * 2 + 300} height={R * 2 + 120} viewBox={`${-R - 150} ${-R - 60} ${R * 2 + 300} ${R * 2 + 120}`} style={{overflow: 'visible'}}>
      <defs>
        <radialGradient id="globe-shade" cx="40%" cy="35%">
          <stop offset="0%" stopColor="#1d3a44" stopOpacity={0.9} />
          <stop offset="100%" stopColor="#081218" stopOpacity={0.95} />
        </radialGradient>
      </defs>
      <circle r={R} fill="url(#globe-shade)" stroke={C.hud} strokeOpacity={0.4} strokeWidth={2} />
      <circle r={R + 26} fill="none" stroke={C.hud} strokeOpacity={0.15} strokeWidth={1.5} strokeDasharray="3 9" transform={`rotate(${frame * 0.2})`} />
      {dots}
      {pins.map((pin) => {
        const p = project(pin.lat, pin.lon, lon0, lat0, R);
        if (p.z <= 0.05 || pin.on <= 0.01) return null;
        const pulse = (frame % 40) / 40;
        const focus = pin.focus ?? 1;
        // 失焦的地点只留一个小点，标签彻底隐藏，避免和下一个地点的标签叠在一起
        const labelO = Math.max(0, focus * 2 - 1);
        return (
          <g key={pin.label} transform={`translate(${p.x}, ${p.y})`} opacity={pin.on * Math.min(1, p.z * 2)}>
            <circle r={16 + pulse * 40} fill="none" stroke={pin.color} strokeWidth={3} opacity={(1 - pulse) * labelO} />
            <circle r={6 + 6 * focus} fill={pin.color} stroke="#fff" strokeWidth={1 + 2 * focus} />
            <g opacity={labelO}>
              <line x1={0} y1={0} x2={60} y2={-70} stroke={pin.color} strokeWidth={2.5} />
              <text x={66} y={-76} style={{fontFamily: FONT.sans, fontWeight: 900, fontSize: 34}} fill={pin.color}>
                {pin.label}
              </text>
            </g>
          </g>
        );
      })}
    </svg>
  );
};
